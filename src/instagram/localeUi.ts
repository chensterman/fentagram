function suffixPattern(parts: string[]): RegExp {
  const escaped = [...new Set(parts.map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')))].join('|')
  return new RegExp(`^\\d[\\d,.\\s]*(?:k|m|K|M)?\\s*(?:${escaped})`, 'iu')
}

/** Fallback when href-based count links are missing (localized suffixes). */
export function countLinkPattern(list: ListName): RegExp {
  return suffixPattern(list === 'followers' ? FOLLOWER_COUNT_SUFFIXES : FOLLOWING_COUNT_SUFFIXES)
}

